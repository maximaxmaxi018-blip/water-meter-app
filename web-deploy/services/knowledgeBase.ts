// Функция для поиска подходящего ответа
export function findKnowledgeAnswer(userText: string): string | null {
  const lowerText = userText.toLowerCase();
  
  // Сортируем ответы по приоритету (выше приоритет = выше в списке)
  const sortedAnswers = KNOWLEDGE_BASE.sort((a, b) => b.priority - a.priority);
  
  // Ищем первый подходящий ответ
  for (const answer of sortedAnswers) {
    for (const pattern of answer.patterns) {
      if (pattern.test(lowerText)) {
        return answer.response;
      }
    }
  }
  
  return null;
}
